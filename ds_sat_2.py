upper_limit = Q3 + 1.5 * IQR

outliers = (
    (billing["monthly_bill"] < lower_limit) |
    (billing["monthly_bill"] > upper_limit)
).sum()

billing["monthly_bill"] = billing["monthly_bill"].clip(
    lower=lower_limit,
    upper=upper_limit
)

print("Billing Outliers Treated:", outliers)
