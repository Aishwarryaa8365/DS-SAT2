from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.metrics import confusion_matrix, classification_report

# Create a new feature
combined["complaints_per_tenure"] = (
    combined["complaints"] /
    combined["tenure"].clip(lower=1)
)

# Select input features
features = [
    "age", "tenure", "plan", "region",
    "monthly_charges", "monthly_data_gb",
    "monthly_voice_min", "sms_count",
    "late_payments", "complaints",
    "network_issues", "outages",
    "plan_changes", "complaints_per_tenure"
]

X = combined[features]
y = combined["churn_flag"]

print("Selected Input Features:")
print(features)

print("\nTarget Variable: Customer Churn")
print("Input Data Shape:", X.shape)
print("Target Data Shape:", y.shape)

# Separate numeric and categorical features
numeric_features = X.select_dtypes(
    include=["number"]
).columns.tolist()

categorical_features = X.select_dtypes(
    exclude=["number"]
).columns.tolist()

# Preprocessing pipeline
numeric_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer([
    ("numeric", numeric_pipeline, numeric_features),
    ("categorical", categorical_pipeline, categorical_features)
])

# Create the model
model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", LogisticRegression(
        max_iter=1000,
        class_weight="balanced"
    ))
])

# Split training and testing data
